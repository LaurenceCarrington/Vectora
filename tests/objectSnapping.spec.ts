  await expect(page.locator('[data-snap-options]')).toHaveCount(0);
  const magnet=page.getByRole('button',{name:'Snapping',exact:true});
  const settings=page.getByRole('button',{name:'Settings',exact:true});
  await settings.click();const dialog=page.getByRole('dialog',{name:'Preferences',exact:true});
  for(const name of ['Intersection','Nearest','Centre','Tangent','Perpendicular'])await dialog.getByRole('switch',{name,exact:true}).check();
  await page.keyboard.press('Escape');
  await page.evaluate(()=>{const e=(window as any).__vectora,p=(window as any).__paper;p.view.center=new p.Point(0,0);e.addShape(new p.Path.Circle({center:[0,0],radius:20,insert:false}),'Circle');e.setTool('line');});
