  expect(await page.evaluate(()=>{const s=(window as any).__vectora.selected;return [s.lastSegment.point.x,s.lastSegment.point.y];})).toEqual(preview);
  expect(await page.evaluate(()=>(window as any).__vectora.activeObjectSnap)).toBeNull();
  const after=await page.evaluate(()=>(window as any).__vectora.objects.length);await page.keyboard.press('Control+z');expect(await page.evaluate(()=>(window as any).__vectora.objects.length)).toBe(after-1);await page.keyboard.press('Control+Shift+z');
  await page.evaluate(()=>{const e=(window as any).__vectora;e.setObjectSnap('perpendicular',false);e.setObjectSnap('tangent',true);});
  await page.keyboard.press('p');await mouse(-50,0);await page.mouse.down();await page.mouse.up();await mouse(-8,Math.sqrt(336));
  await expect.poll(()=>page.evaluate(()=>(window as any).__vectora.activeObjectSnap?.mode)).toBe('tangent');
  await page.mouse.down();await page.mouse.up();await page.keyboard.press('Enter');
  expect(await page.evaluate(()=>(window as any).__vectora.selected.segments.length)).toBe(2);
